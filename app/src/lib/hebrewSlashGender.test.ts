describe("pre-review H1 — every slash form in use resolves to a real word for both genders (table-driven)", () => {
  const sources = ["../content/practices.ts", "./i18nElevation/milestoneCatalogue.ts"];
  const PAIR = /[א-ת]+\/[א-ת]+/g;
  const inUse = async (): Promise<Set<string>> => {
    const fs = await import("node:fs");
    const path = await import("node:path");
    const out = new Set<string>();
    for (const rel of sources) for (const m of fs.readFileSync(path.resolve(__dirname, rel), "utf8").matchAll(PAIR)) out.add(m[0]);
    return out;
  };

  it("every form used in the practice library and the catalogue has a row (a new form must be written here first)", async () => {
    const table = new Set(SLASH_TABLE.map(([form]) => form));
    const forms = await inUse();
    expect(forms.size).toBeGreaterThan(200);
    expect([...forms].filter((f) => !table.has(f))).toEqual([]);
  });

  it("each row resolves exactly: masculine for a boy and with no gender on file, feminine for a girl", () => {
    const wrong: string[] = [];
    for (const [form, m, f] of [...SLASH_TABLE, ...IRREGULAR_ROWS]) {
      for (const g of ["boy", undefined, null]) if (resolveHebrewSlash(form, g) !== m) wrong.push(`${form} ${String(g)} → ${resolveHebrewSlash(form, g)} (want ${m})`);
      if (resolveHebrewSlash(form, "girl") !== f) wrong.push(`${form} girl → ${resolveHebrewSlash(form, "girl")} (want ${f})`);
    }
    expect(wrong).toEqual([]);
  });

  it("the irregulars, in sentences the parent reads (R01): a boy is 'אתה מדבר', a girl 'את מדברת'; never 'תראהי' / 'תרצהי'", () => {
    expect(resolveHebrewSlash("וואו, את/ה מדבר/ת איתי!", "boy")).toBe("וואו, אתה מדבר איתי!");
    expect(resolveHebrewSlash("וואו, את/ה מדבר/ת איתי!", "girl")).toBe("וואו, את מדברת איתי!");
    expect(resolveHebrewSlash("תראה/י את הכדור!", "girl")).toBe("תראי את הכדור!");
    expect(resolveHebrewSlash("תרצה/י עוד?", "girl")).toBe("תרצי עוד?");
    expect(resolveHebrewSlash("כשהוא/היא מצביע/ה", "girl")).toBe("כשהיא מצביעה");
    for (const g of ["girl", "boy"]) {
      const out = SLASH_TABLE.map(([form]) => resolveHebrewSlash(form, g)).join(" ");
      expect(out, g).not.toMatch(/הי(?=\s|$)|תהי\b/);
    }
  });

  it("already-correct forms keep their behaviour (pins)", () => {
    const g = (s: string) => resolveHebrewSlash(s, "girl");
    expect(g("הוא/היא")).toBe("היא");
    expect(g("לו/לה")).toBe("לה");
    expect(g("לך/לכי")).toBe("לכי");
    expect(g("יוכל/תוכל")).toBe("תוכל");
    expect(g("בוא/י")).toBe("בואי");
    expect(g("שומר/שומרת")).toBe("שומרת");
    expect(g("שלו/שלה")).toBe("שלה");
  });
});

