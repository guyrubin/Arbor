#!/usr/bin/env node
/**
 * plan-plate-manifest — the build-time list of the plan plates committed under
 * public/visuals/plans/<patternId>/<plateId>.webp, written to
 * src/lib/library/plans/planPlateManifest.ts (B-BOOK-75 plates in-product):
 * a plate in the list resolves to its static path, any other to the
 * shared-storage GET route. Runs first in `npm run build`; `--check` exits 1
 * when the committed manifest drifts from the folder (the vitest guard,
 * scripts/planPlateManifest.test.ts, does the same).
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
export const APP_ROOT = path.resolve(here, "..");
export const PLATES_DIR = path.join(APP_ROOT, "public", "visuals", "plans");
export const MANIFEST_FILE = path.join(APP_ROOT, "src", "lib", "library", "plans", "planPlateManifest.ts");

const ID = /^[A-Za-z0-9_-]{1,64}$/;

/** `<patternId>/<plateId>` for every committed `.webp`, sorted. */
export function scanCommittedPlanPlates(dir = PLATES_DIR) {
  if (!existsSync(dir)) return [];
  const out = [];
  for (const pattern of readdirSync(dir, { withFileTypes: true })) {
    if (!pattern.isDirectory() || !ID.test(pattern.name)) continue;
    for (const f of readdirSync(path.join(dir, pattern.name), { withFileTypes: true })) {
      const m = f.isFile() && /^([A-Za-z0-9_-]{1,64})\.webp$/.exec(f.name);
      if (m) out.push(`${pattern.name}/${m[1]}`);
    }
  }
  return out.sort();
}

export function renderManifest(ids) {
  const list = ids.length ? `[\n${ids.map((id) => `  ${JSON.stringify(id)},`).join("\n")}\n]` : "[]";
  return `/**
 * lib/library/plans/planPlateManifest — GENERATED by
 * \`node scripts/plan-plate-manifest.mjs\` (part of \`npm run build\`); do not
 * edit by hand. The plan plates committed under \`public/visuals/plans/
 * <patternId>/<plateId>.webp\` at build time, as \`<patternId>/<plateId>\`.
 * A plate listed here resolves to its static path; every other plate resolves
 * to the shared-storage route GET /api/plans/plates/:pattern/:plate
 * (lib/library/plans/planPlates.planPlateFile). scripts/planPlateManifest.test.ts
 * fails when this list drifts from the folder.
 */
export const COMMITTED_PLAN_PLATES: readonly string[] = ${list};
`;
}

function main() {
  const check = process.argv.includes("--check");
  const next = renderManifest(scanCommittedPlanPlates());
  const current = existsSync(MANIFEST_FILE) ? readFileSync(MANIFEST_FILE, "utf8") : "";
  if (next === current) {
    console.log(`plan-plate-manifest: up to date (${scanCommittedPlanPlates().length} committed plate(s))`);
    return;
  }
  if (check) {
    console.error("plan-plate-manifest: src/lib/library/plans/planPlateManifest.ts drifts from public/visuals/plans — run `node scripts/plan-plate-manifest.mjs`");
    process.exit(1);
  }
  writeFileSync(MANIFEST_FILE, next);
  console.log(`plan-plate-manifest: wrote ${path.relative(APP_ROOT, MANIFEST_FILE)}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
